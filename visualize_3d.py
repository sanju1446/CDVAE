def show_crystal(filepath=None, result=None, title=None, height=520):
    """
    Show an interactive 3D crystal structure viewer inline in Jupyter/Kaggle.

    Args:
        filepath : path to a .cif file (e.g. "generated/sample_1.cif")
        result   : dict returned by model.generate() — use instead of filepath
        title    : optional title string
        height   : viewer height in px (default 520)
    """
    import uuid
    uid = uuid.uuid4().hex[:8]

    if result is not None:
        scene = result_to_scene(result)
    elif filepath is not None:
        scene = parse_cif(filepath)
        scene["energy"]   = None
        scene["ehull"]    = None
        scene["band_gap"] = None
    else:
        raise ValueError("Provide either filepath= or result=")

    # Info panel
    p = scene["params"]
    info_html = (
        f"<b>Lattice</b><br>"
        f"a={p['a']:.3f} b={p['b']:.3f} c={p['c']:.3f} Å<br>"
        f"α={p['alpha']:.1f}° β={p['beta']:.1f}° γ={p['gamma']:.1f}°<br>"
        f"Atoms: {len(scene['atoms'])}"
    )
    if title:
        info_html = f"<b style='color:#58a6ff'>{title}</b><br>" + info_html

    # Property chips
    prop_chips = ""
    if scene.get("energy") is not None:
        prop_chips += f'<div class="cv-chip-{uid}">Formation energy <span>{scene["energy"]:+.3f} eV/at</span></div>'
    if scene.get("ehull") is not None:
        e = scene["ehull"]
        stab = "Stable" if e < 0.025 else ("Metastable" if e < 0.1 else "Unstable")
        col  = "#3fb950" if e < 0.025 else ("#d29922" if e < 0.1 else "#f85149")
        prop_chips += f'<div class="cv-chip-{uid}">E above hull <span style="color:{col}">{e:+.4f} eV/at ({stab})</span></div>'
    if scene.get("band_gap") is not None:
        bg = scene["band_gap"]
        prop_chips += f'<div class="cv-chip-{uid}">Band gap <span>{bg:.3f} eV</span></div>'

    html = HTML_TEMPLATE.format(
        uid        = uid,
        scene_json = json.dumps(scene),
        elem_json  = json.dumps(ELEMENT_DATA),
        info_html  = info_html,
        prop_chips = prop_chips,
    )
    display(HTML(html))


# ── Convenience: show all results from generate() ────────────────────────────

def show_all(results, elements=None):
    """Show all structures from model.generate() in 3D, one after another."""
    for i, r in enumerate(results):
        comp = {}
        for s in r["symbols"]:
            comp[s] = comp.get(s, 0) + 1
        formula = "".join(f"{el}{n if n>1 else ''}" for el, n in sorted(comp.items()))
        t = f"Sample #{i+1} — {formula}"
        print(f"\n{'='*50}")
        print(f"  {t}")
        print(f"  Atoms: {r['n_atoms']}  |  "
              f"Energy: {r['energy']:+.3f} eV/at  |  "
              f"E_hull: {r['ehull']:+.4f} eV/at  |  "
              f"Band gap: {r['band_gap']:.3f} eV")
        print(f"{'='*50}")
        show_crystal(result=r, title=t)