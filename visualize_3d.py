# ── CIF parser ────────────────────────────────────────────────────────────────

def parse_cif(filepath):
    """Parse minimal CIF file → lattice matrix + atom list."""
    params = {}
    atoms  = []
    in_loop = False
    cols    = []

    with open(filepath) as f:
        lines = f.readlines()

    for line in lines:
        line = line.strip()
        if not line or line.startswith("#"):
            continue

        # Lattice parameters
        for key in ["_cell_length_a", "_cell_length_b", "_cell_length_c",
                    "_cell_angle_alpha", "_cell_angle_beta", "_cell_angle_gamma"]:
            if line.startswith(key):
                try:
                    params[key] = float(line.split()[-1].split("(")[0])
                except:
                    pass

        if "loop_" in line:
            in_loop = True
            cols    = []
            continue

        if in_loop:
            if line.startswith("_atom_site"):
                cols.append(line.strip())
                continue
            elif line.startswith("_") :
                in_loop = False
                cols    = []
                continue
            elif cols:
                parts = line.split()
                if len(parts) >= len(cols) and len(cols) >= 4:
                    try:
                        row = dict(zip(cols, parts))
                        sym = row.get("_atom_site_type_symbol",
                              row.get("_atom_site_label", "X"))
                        sym = "".join(c for c in sym if c.isalpha())[:2].capitalize()
                        x   = float(row.get("_atom_site_fract_x", 0))
                        y   = float(row.get("_atom_site_fract_y", 0))
                        z   = float(row.get("_atom_site_fract_z", 0))
                        atoms.append({"sym": sym, "frac": [x, y, z]})
                    except:
                        pass

    # Build lattice matrix from a,b,c,α,β,γ
    a  = params.get("_cell_length_a", 4.0)
    b  = params.get("_cell_length_b", 4.0)
    c  = params.get("_cell_length_c", 4.0)
    al = math.radians(params.get("_cell_angle_alpha", 90.0))
    be = math.radians(params.get("_cell_angle_beta",  90.0))
    ga = math.radians(params.get("_cell_angle_gamma", 90.0))

    sg = math.sin(ga)
    cg = math.cos(ga)
    cb = math.cos(be)
    ca = math.cos(al)

    # Standard crystallographic → Cartesian conversion
    v  = math.sqrt(max(1 - ca**2 - cb**2 - cg**2 + 2*ca*cb*cg, 1e-10))
    L  = [
        [a,         b*cg,                      c*cb],
        [0,         b*sg,                      c*(ca - cb*cg)/max(sg, 1e-10)],
        [0,         0,                         c*v/max(sg, 1e-10)],
    ]

    # Fractional → Cartesian
    cart_atoms = []
    for atom in atoms:
        fx, fy, fz = atom["frac"]
        cx = L[0][0]*fx + L[0][1]*fy + L[0][2]*fz
        cy =              L[1][1]*fy + L[1][2]*fz
        cz =                           L[2][2]*fz
        cart_atoms.append({
            "sym"  : atom["sym"],
            "pos"  : [round(cx, 4), round(cy, 4), round(cz, 4)],
            "frac" : [round(fx, 4), round(fy, 4), round(fz, 4)],
        })

    # Lattice vectors for unit-cell wireframe
    lattice_vecs = [
        [round(L[0][0], 4), 0,                  0                 ],
        [round(L[0][1], 4), round(L[1][1], 4),  0                 ],
        [round(L[0][2], 4), round(L[1][2], 4),  round(L[2][2], 4)],
    ]

    return {
        "atoms"       : cart_atoms,
        "lattice_vecs": lattice_vecs,
        "params"      : {
            "a": a, "b": b, "c": c,
            "alpha": math.degrees(al),
            "beta" : math.degrees(be),
            "gamma": math.degrees(ga),
        },
    }


def result_to_scene(result):
    """Convert generate() result dict → scene dict (bypasses CIF)."""
    L    = result["lattice"]
    atoms = []
    for sym, pos, frac in zip(result["symbols"],
                               result["cartesian"],
                               result["frac_coords"]):
        atoms.append({
            "sym" : sym,
            "pos" : [round(float(p), 4) for p in pos],
            "frac": [round(float(f), 4) for f in frac],
        })

    lattice_vecs = [
        [round(float(L[0][0]), 4), round(float(L[1][0]), 4), round(float(L[2][0]), 4)],
        [round(float(L[0][1]), 4), round(float(L[1][1]), 4), round(float(L[2][1]), 4)],
        [round(float(L[0][2]), 4), round(float(L[1][2]), 4), round(float(L[2][2]), 4)],
    ]

    a = float(np.linalg.norm(L[0]))
    b = float(np.linalg.norm(L[1]))
    c = float(np.linalg.norm(L[2]))
    cos_al = float(np.dot(L[1], L[2]) / (b * c + 1e-8))
    cos_be = float(np.dot(L[0], L[2]) / (a * c + 1e-8))
    cos_ga = float(np.dot(L[0], L[1]) / (a * b + 1e-8))

    return {
        "atoms"       : atoms,
        "lattice_vecs": lattice_vecs,
        "params": {
            "a": round(a, 3), "b": round(b, 3), "c": round(c, 3),
            "alpha": round(math.degrees(math.acos(np.clip(cos_al, -1, 1))), 2),
            "beta" : round(math.degrees(math.acos(np.clip(cos_be, -1, 1))), 2),
            "gamma": round(math.degrees(math.acos(np.clip(cos_ga, -1, 1))), 2),
        },
        "energy"  : result.get("energy", None),
        "ehull"   : result.get("ehull", None),
        "band_gap": result.get("band_gap", None),
    }


